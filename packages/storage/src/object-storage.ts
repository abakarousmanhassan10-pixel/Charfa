import type { Readable } from 'stream';

export interface StoredObject {
  body: Readable;
  contentType?: string;
  contentLength?: number;
  contentRange?: string;
  partial: boolean;
}

export type StorageErrorKind = 'not_found' | 'access_denied' | 'bucket_missing' | 'unavailable' | 'invalid_config' | 'unknown';

/** Provider failures mapped to a small set of kinds. Messages never contain credentials. */
export class StorageError extends Error {
  constructor(
    readonly kind: StorageErrorKind,
    message: string,
  ) {
    super(message);
    this.name = 'StorageError';
  }
}

export class StorageNotConfiguredError extends Error {
  constructor() {
    super('Media storage is not configured (S3_BUCKET, S3_REGION, S3_ACCESS_KEY_ID, S3_SECRET_ACCESS_KEY)');
    this.name = 'StorageNotConfiguredError';
  }
}

/**
 * Provider-neutral object storage. Production: S3-compatible (AWS S3, Cloudflare R2, MinIO).
 * Keys are generated by the server only and always prefixed with the owning business id.
 * Objects are private; access goes through signed URLs.
 */
export interface ObjectStorage {
  readonly configured: boolean;
  /** Human-readable provider label for health/status output (never includes secrets). */
  readonly description: string;
  put(key: string, body: Buffer | Readable, opts: { contentType: string; contentLength?: number }): Promise<void>;
  get(key: string, range?: string): Promise<StoredObject>;
  head(key: string): Promise<{ size: number; contentType?: string } | null>;
  delete(key: string): Promise<void>;
  /** Short-lived presigned GET URL issued by the provider itself. */
  presignGet(key: string, expiresInSeconds: number): Promise<string>;
}

export const OBJECT_STORAGE = Symbol('OBJECT_STORAGE');
