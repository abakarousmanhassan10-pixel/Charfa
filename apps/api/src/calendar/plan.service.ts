import { BadRequestException, ConflictException, Injectable, NotFoundException } from '@nestjs/common';
import type { ContentPlan } from '@touma/ai-engine';
import { Prisma, type ContentPillar, type SocialPlatform } from '@touma/database';
import { AI_LANGUAGES, CALENDAR_LIMITS, addDays, diffDays, isValidDate, todayIn, type AiLanguage, type AiPlatform, type AiTone, type TimeSource } from '@touma/shared';
import { AuditService } from '../audit/audit.service';
import { AiHistoryService } from '../ai/ai-history.service';
import { AiOrchestratorService } from '../ai/orchestrator.service';
import { PrismaService } from '../prisma/prisma.service';
import type { TenantContext } from '../tenancy/tenant-context';
import type { ApplyPlanDto, CreatePlanDto } from './calendar.dto';
import { CalendarService } from './calendar.service';
import { SchedulingService } from './scheduling.service';

/**
 * AI marketing plans. A plan is generated by the TOUMA AI pipeline (background job, grounding, usage limits) and only
 * enters the calendar when a person applies it. Applied entries are DRAFTs: they still need approval and authorization.
 */
@Injectable()
export class PlanService {
  constructor(
    private readonly prisma: PrismaService,
    private readonly calendar: CalendarService,
    private readonly scheduling: SchedulingService,
    private readonly orchestrator: AiOrchestratorService,
    private readonly history: AiHistoryService,
    private readonly audit: AuditService,
  ) {}

  /** Queues the plan generation. Dates are validated in the business timezone. */
  async submit(tenant: TenantContext, dto: CreatePlanDto) {
    const bt = await this.calendar.businessTime(tenant.businessId);
    if (!isValidDate(dto.startDate)) throw new BadRequestException({ code: 'INVALID_TIME', message: 'startDate is not a valid date' });
    const today = todayIn(bt.timezone);
    if (diffDays(today, dto.startDate) < 0) throw new BadRequestException({ code: 'START_IN_PAST', message: 'The plan cannot start in the past' });
    const names = new Set<string>();
    const occasions = (dto.occasions ?? []).map((o) => {
      if (!isValidDate(o.date)) throw new BadRequestException({ code: 'INVALID_OCCASION', message: `Occasion "${o.name}" has an invalid date` });
      const day = diffDays(dto.startDate, o.date) + 1;
      if (day < 1 || day > dto.days) throw new BadRequestException({ code: 'INVALID_OCCASION', message: `Occasion "${o.name}" is outside the plan (${dto.startDate} to ${addDays(dto.startDate, dto.days - 1)})` });
      const key = o.name.trim().toLowerCase();
      if (names.has(key)) throw new BadRequestException({ code: 'INVALID_OCCASION', message: `Occasion "${o.name}" is listed twice` });
      names.add(key);
      return { name: o.name, date: o.date, day };
    });
    const language = (dto.language && (AI_LANGUAGES as readonly string[]).includes(dto.language) ? dto.language : bt.locale) as AiLanguage;
    const gen = await this.orchestrator.submit(tenant, {
      task: 'CONTENT_PLAN', language, startDate: dto.startDate, days: dto.days, postsPerWeek: dto.postsPerWeek, platforms: dto.platforms as AiPlatform[], tone: (dto.tone as AiTone) ?? null, goal: dto.goal ?? null, occasions, instructions: dto.instructions,
    });
    return gen;
  }

  list(tenant: TenantContext, q: { page: number; pageSize: number }) {
    return this.history.list(tenant, { ...q, task: 'CONTENT_PLAN' } as never);
  }

  private async loadGeneration(tenant: TenantContext, id: string) {
    const g = await this.prisma.aIGeneration.findFirst({ where: { id, businessId: tenant.businessId, task: 'CONTENT_PLAN' } });
    if (!g) throw new NotFoundException({ code: 'GENERATION_NOT_FOUND', message: 'Plan not found' });
    if (g.status !== 'SUCCEEDED' || !g.output) throw new ConflictException({ code: 'PLAN_NOT_READY', message: 'This plan is not finished' });
    return g;
  }

  /**
   * Proposes a date and time for each item: the day comes from the plan, the time from this business's measured
   * audience data when there is enough of it, otherwise from labelled estimates. Times already used on the same
   * platform and day are avoided.
   */
  private async propose(db: Prisma.TransactionClient | PrismaService, tenant: TenantContext, plan: ContentPlan, skip: Set<number>) {
    const bt = await this.calendar.businessTime(tenant.businessId);
    const notBefore = new Date(Date.now() + CALENDAR_LIMITS.minLeadMinutes * 60_000);
    const taken = new Map<string, Date[]>();
    const order = plan.items.map((it, index) => ({ it, index })).sort((a, b) => a.it.day - b.it.day || a.index - b.index);
    const out: Array<{ index: number; day: number; date: string; at: Date | null; source: TimeSource; note: string | null }> = [];
    for (const { it, index } of order) {
      if (skip.has(index)) continue;
      const platform = it.platform as SocialPlatform;
      let placed: { at: Date; source: TimeSource; note: string | null; date: string } | null = null;
      for (let extra = 0; extra <= 2 && !placed; extra++) {
        const date = addDays(plan.startDate, it.day - 1 + extra);
        const free = await this.scheduling.firstFreeSlot(db, { businessId: tenant.businessId, platform, date, timezone: bt.timezone, notBefore, taken: taken.get(platform) ?? [] });
        if (free && free.rec.date === date) placed = { at: free.at, source: free.rec.source, note: extra ? `${free.rec.note} Moved ${extra} day(s) later because the planned day had no free time.` : free.rec.note, date };
      }
      if (placed) taken.set(platform, [...(taken.get(platform) ?? []), placed.at]);
      out.push({ index, day: it.day, date: placed?.date ?? addDays(plan.startDate, it.day - 1), at: placed?.at ?? null, source: placed?.source ?? 'ESTIMATE', note: placed?.note ?? 'No free time found for this post' });
    }
    return { timezone: bt.timezone, proposals: out };
  }

  /** The plan with a proposed time for every post (nothing is created). */
  async preview(tenant: TenantContext, generationId: string) {
    const g = await this.loadGeneration(tenant, generationId);
    const plan = g.output as unknown as ContentPlan;
    const applied = await this.prisma.contentPlan.findUnique({ where: { generationId: g.id }, select: { id: true } });
    const { timezone, proposals } = await this.propose(this.prisma, tenant, plan, new Set());
    return {
      generationId: g.id,
      appliedPlanId: applied?.id ?? null,
      timezone,
      plan: { language: plan.language, startDate: plan.startDate, days: plan.days, summary: plan.summary, warnings: plan.warnings, missingInformation: plan.missingInformation },
      items: plan.items.map((it, index) => {
        const p = proposals.find((x) => x.index === index);
        return { index, ...it, proposed: p && { date: p.date, scheduledAt: p.at?.toISOString() ?? null, source: p.source, note: p.note } };
      }),
      balance: plan.items.reduce<Record<string, number>>((m, it) => ({ ...m, [it.pillar]: (m[it.pillar] ?? 0) + 1 }), {}),
    };
  }

  /** Puts the reviewed plan on the calendar as DRAFT entries. Applying the same plan twice is rejected. */
  async apply(tenant: TenantContext, generationId: string, dto: ApplyPlanDto) {
    const g = await this.loadGeneration(tenant, generationId);
    const plan = g.output as unknown as ContentPlan;
    const existing = await this.prisma.contentPlan.findUnique({ where: { generationId: g.id }, select: { id: true } });
    if (existing) throw new ConflictException({ code: 'PLAN_ALREADY_APPLIED', message: 'This plan was already applied', planId: existing.id });
    const skip = new Set(dto.skip ?? []);
    const bt = await this.calendar.businessTime(tenant.businessId);
    const platforms = [...new Set(plan.items.filter((_, i) => !skip.has(i)).map((i) => i.platform))].sort() as SocialPlatform[];
    try {
      const out = await this.prisma.$transaction(
        async (tx) => {
          for (const p of platforms) await this.scheduling.lock(tx, tenant.businessId, p);
          const record = await tx.contentPlan.create({ data: { businessId: tenant.businessId, generationId: g.id, name: `Plan ${plan.startDate}`, startDate: plan.startDate, days: plan.days, timezone: bt.timezone, language: plan.language, summary: plan.summary, itemCount: 0, createdById: tenant.userId } });
          const { proposals } = await this.propose(tx, tenant, plan, skip);
          let created = 0;
          let unplaced = 0;
          for (const p of proposals) {
            if (!p.at) { unplaced++; continue; }
            const it = plan.items[p.index]!;
            await this.calendar.insertEntry(tx, tenant, bt, {
              title: it.title, platform: it.platform as SocialPlatform, at: p.at, source: p.source, timeNote: p.note, pillar: it.pillar as ContentPillar, brief: it.brief, occasion: it.occasion, contentType: it.contentType, language: plan.language,
              origin: 'AI_ASSISTED', productId: it.itemType === 'PRODUCT' ? it.itemId : null, serviceId: it.itemType === 'SERVICE' ? it.itemId : null, planId: record.id,
              aiMetadata: { plan: { generationId: g.id, index: p.index }, promptVersion: g.promptVersion } as Prisma.InputJsonValue,
            });
            created++;
          }
          await tx.contentPlan.update({ where: { id: record.id }, data: { itemCount: created } });
          return { planId: record.id, created, unplaced };
        },
        { timeout: 60_000 },
      );
      await this.audit.record({ action: 'calendar.plan_applied', actorId: tenant.userId, businessId: tenant.businessId, entityType: 'ContentPlan', entityId: out.planId, metadata: { generationId: g.id, created: out.created, unplaced: out.unplaced, skipped: skip.size } });
      return { ...out, skipped: skip.size };
    } catch (err) {
      // Two people applying the same plan at once: the unique generation id lets exactly one win.
      if (err instanceof Prisma.PrismaClientKnownRequestError && err.code === 'P2002') {
        const winner = await this.prisma.contentPlan.findUnique({ where: { generationId: g.id }, select: { id: true } });
        throw new ConflictException({ code: 'PLAN_ALREADY_APPLIED', message: 'This plan was already applied', planId: winner?.id });
      }
      throw err;
    }
  }

  async plans(tenant: TenantContext) {
    const items = await this.prisma.contentPlan.findMany({ where: { businessId: tenant.businessId }, orderBy: { createdAt: 'desc' }, take: 20 });
    return { items: items.map((p) => ({ id: p.id, generationId: p.generationId, name: p.name, startDate: p.startDate, days: p.days, language: p.language, itemCount: p.itemCount, createdAt: p.createdAt.toISOString() })) };
  }
}
